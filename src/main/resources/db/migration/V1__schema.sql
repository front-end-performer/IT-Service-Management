-- Portable between PostgreSQL and H2 (PostgreSQL mode).

create table provider (
    id       varchar(64)  primary key,
    name     varchar(255) not null,
    capacity integer      not null check (capacity > 0)
);

create table service_offering (
    id               bigint generated by default as identity primary key,
    provider_id      varchar(64)  not null references provider (id),
    code             varchar(32)  not null,
    name             varchar(255) not null,
    duration_minutes integer      not null check (duration_minutes > 0),
    constraint uq_service_offering_provider_code unique (provider_id, code)
);

create table import_batch (
    id          varchar(36)  primary key,
    provider_id varchar(64)  not null references provider (id),
    file_name   varchar(255),
    imported_at timestamp with time zone not null,
    total_rows  integer      not null,
    imported    integer      not null,
    duplicates  integer      not null,
    rejected    integer      not null
);

create table import_rejection (
    id          bigint generated by default as identity primary key,
    batch_id    varchar(36)  not null references import_batch (id),
    line_number integer      not null,
    raw_line    varchar(1000),
    reason      varchar(32)  not null,
    message     varchar(500) not null
);

create table appointment (
    id                varchar(36)  primary key,
    provider_id       varchar(64)  not null references provider (id),
    service_offering_id bigint       not null references service_offering (id),
    customer_number   varchar(64)  not null,
    start_at          timestamp with time zone not null,
    end_at            timestamp with time zone not null,
    source            varchar(16)  not null,
    import_batch_id   varchar(36)  references import_batch (id),
    created_at        timestamp with time zone not null,
    constraint ck_appointment_interval check (end_at > start_at),
    constraint uq_appointment_natural_key unique (provider_id, service_offering_id, customer_number, start_at)
);

create index ix_appointment_provider_time on appointment (provider_id, start_at, end_at);
create index ix_import_rejection_batch on import_rejection (batch_id);
